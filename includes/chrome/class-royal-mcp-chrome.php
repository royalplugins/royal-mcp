    public function filter_update_footer( $content ) {
        if ( ! $this->is_royal_mcp_admin_page() ) {
            return $content;
        }
        // A companion plugin can put its own name and version in the footer stamp.
        $wordmark = apply_filters( 'royal_mcp_chrome_wordmark', __( 'Royal MCP', 'royal-mcp' ) );
        $version  = apply_filters(
            'royal_mcp_chrome_version',
            defined( 'ROYAL_MCP_VERSION' ) ? ROYAL_MCP_VERSION : ''
        );
        $wordmark = is_string( $wordmark ) ? $wordmark : 'Royal MCP';
        $version  = is_string( $version ) ? $version : '';
        return sprintf(
            /* translators: 1: plugin display name, 2: plugin version */
            esc_html__( '%1$s v%2$s', 'royal-mcp' ),
            esc_html( $wordmark ),
            esc_html( $version )
        );
    }

    /* ==================================================================
     *  Side-menu upgrade entry
     * ================================================================ */

    /** The "Upgrade" entry in the side menu, which leads to the Royally page. */
    public function register_upgrade_menu(): void {
        add_submenu_page(
            'royal-mcp',
            __( 'Royal MCP Pro', 'royal-mcp' ),
            '<span class="royal-mcp-upgrade-menu-text">' . esc_html__( 'Upgrade To Pro', 'royal-mcp' ) . '</span>',
            'manage_options',
            self::UPGRADE_MENU_SLUG,
            '__return_true'
        );

        // A submenu entry takes a page slug; the slug is swapped for the outside address.
        global $submenu;
        if ( isset( $submenu['royal-mcp'] ) ) {
            foreach ( $submenu['royal-mcp'] as $idx => $item ) {
                if ( isset( $item[2] ) && self::UPGRADE_MENU_SLUG === $item[2] ) {
                    $submenu['royal-mcp'][ $idx ][2] = $this->campaign_url( self::ROYALLY_URL_BASE, 'admin_menu_upgrade' ); // phpcs:ignore WordPress.WP.GlobalVariablesOverride.Prohibited -- the menu API has no outside links
                }
            }
        }
    }

    /**
     * The menu API has no link attributes, so a small script makes the upgrade
     * entry, and only that entry, open in a new tab.
     */
    public function inject_upgrade_menu_target_blank(): void {
        if ( ! is_admin() ) {
            return;
        }
        $js = sprintf(
            '(function(){var links=document.querySelectorAll("#adminmenu a");for(var i=0;i<links.length;i++){if((links[i].getAttribute("href")||"").indexOf(%s)!==-1){links[i].setAttribute("target","_blank");links[i].setAttribute("rel","noopener noreferrer");}}})();',
            wp_json_encode( 'utm_content=admin_menu_upgrade' )
        );
        wp_add_inline_script( 'common', $js );
    }

