<?php
/**
 * Royal Plugins Chrome Pack — Royal MCP edition.
 *
 * Renders the family-wide admin chrome on every Royal MCP admin surface:
 *   1. Custom top header (logo + wordmark + View Docs / Support buttons)
 *   2. Lightweight footer (Royal Plugins family links + version marker)
 *   3. The banner under the header and the side-menu upgrade entry
 *   4. The list of Royal plugins shown on the Dashboard
 *
 * Screen-ID-gated to Royal MCP admin pages only — never touches other WP admin.
 *
 * @package Royal_MCP
 */

namespace Royal_MCP\Chrome;

if ( ! defined( 'ABSPATH' ) ) {
    exit;
}

class Royal_MCP_Chrome {

    const CSS_HANDLE                   = 'royal-mcp-chrome';
    const BODY_CLASS                   = 'royal-mcp-chrome-scope';

