    /**
     * The family list with a state per plugin: here (this plugin), active,
     * inactive (installed, not active) or not_installed. An entry that is not
     * a list with a name and a plugin file is left out; `basename` is set to
     * the file that is installed, so an Activate link points at it.
     */
    public function get_family_plugins_with_state(): array {
        if ( ! function_exists( 'get_plugins' ) ) {
            require_once ABSPATH . 'wp-admin/includes/plugin.php';
        }
        $all_installed = array_keys( get_plugins() );
        $family        = $this->get_family_plugins();
        $current       = defined( 'ROYAL_MCP_PLUGIN_BASENAME' ) ? ROYAL_MCP_PLUGIN_BASENAME : 'royal-mcp/royal-mcp.php';
        $out           = [];
        foreach ( is_array( $family ) ? $family : [] as $slug => $plugin ) {
            if ( ! is_array( $plugin ) || empty( $plugin['name'] ) || ! is_string( $plugin['name'] ) || empty( $plugin['basename'] ) || ! is_string( $plugin['basename'] ) ) {
                continue;
            }
            foreach ( [ 'pitch', 'learn_url', 'install_url', 'search_slug', 'icon', 'badge_label' ] as $field ) {
                if ( isset( $plugin[ $field ] ) && ! is_string( $plugin[ $field ] ) ) {
                    unset( $plugin[ $field ] );
                }
            }
            $files = [ $plugin['basename'] ];
            foreach ( isset( $plugin['also'] ) && is_array( $plugin['also'] ) ? $plugin['also'] : [] as $file ) {
                if ( is_string( $file ) && '' !== $file ) {
                    $files[] = $file;
                }
            }
            $state = 'not_installed';
            foreach ( $files as $file ) {
                if ( ! in_array( $file, $all_installed, true ) ) {
                    continue;
                }
                if ( is_plugin_active( $file ) ) {
                    $state              = 'active';
                    $plugin['basename'] = $file;
                    break;
                }
                if ( 'not_installed' === $state ) {
                    $state              = 'inactive';
                    $plugin['basename'] = $file;
                }
            }
            // This plugin's own entry, whatever folder it runs from.
            $plugin['state']        = ( 'royal-mcp' === $slug || $plugin['basename'] === $current ) ? 'here' : $state;
            $out[ (string) $slug ] = $plugin;
        }
        return $out;
    }
