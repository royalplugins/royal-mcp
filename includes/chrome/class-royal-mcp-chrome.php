    /**
     * The banners that take turns in the thin bar under the header, on this
     * plugin's own screens only. Each has a text, a link label and an address.
     *
     * @return array<string, array{text:string, label:string, url:string}>
     */
    public function banner_slots(): array {
        $slots = [];
        // Someone who already runs Royal MCP Pro has Royally's side covered.
        if ( ! class_exists( '\\Royal_MCP_Pro\\Tool_Registry', false ) ) {
            $slots['royally'] = [
                'text'  => __( 'One MCP connection for all your sites, Cloudflare, UptimeRobot and more, with approvals and undo. Royal MCP Pro comes with it.', 'royal-mcp' ),
                'label' => __( 'Check out Royal MCP Pro', 'royal-mcp' ),
                'url'   => $this->campaign_url( self::ROYALLY_URL_BASE, 'chrome_banner_royally' ),
            ];
        }
        $slots['affiliate'] = [
            'text'  => __( 'Earn 30% recommending Royal Plugins and Royally.', 'royal-mcp' ),
            'label' => __( 'Join the affiliate programme', 'royal-mcp' ),
            'url'   => $this->campaign_url( self::AFFILIATE_URL_BASE, 'chrome_banner_affiliate' ),
        ];
        /**
         * Filters the banners shown in the bar under the header.
         *
         * @param array $slots Slot id => [ text, label, url ].
         */
        $filtered = apply_filters( 'royal_mcp_chrome_banners', $slots );
        $out      = [];
        foreach ( is_array( $filtered ) ? $filtered : $slots as $id => $slot ) {
            if ( is_array( $slot ) && ! empty( $slot['text'] ) && is_string( $slot['text'] ) && ! empty( $slot['label'] ) && is_string( $slot['label'] ) && ! empty( $slot['url'] ) && is_string( $slot['url'] ) ) {
                $out[ (string) $id ] = [ 'text' => $slot['text'], 'label' => $slot['label'], 'url' => $slot['url'] ];
            }
        }
        return $out;
    }

    /** The banner for this week: the slots take turns by week of the year. */
    public function current_banner(): array {
        $slots = $this->banner_slots();
        if ( ! $slots ) {
            return [];
        }
        $ids = array_keys( $slots );
        $id  = $ids[ (int) current_datetime()->format( 'W' ) % count( $ids ) ];
        return [ 'id' => $id ] + $slots[ $id ];
    }

    /** An address on royalplugins.com with this plugin's campaign tags. */
    private function campaign_url( string $base, string $content ): string {
        return add_query_arg(
            [
                'utm_source'   => 'royal_mcp_free',
                'utm_medium'   => 'free_plugin',
                'utm_content'  => $content,
                'utm_campaign' => 'royal_mcp_admin',
            ],
            $base
        );
    }

